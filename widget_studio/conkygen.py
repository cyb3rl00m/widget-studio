"""Turns a Widget into a Conky config file.

Lessons baked in:
- dynamic content comes from files written by our own updater and is shown with
  ${catp}, never with ${execpi} (scripts run inside the Conky AppImage
  environment can fail silently);
- text_buffer_size is raised so long markup (like a calendar) is never cut off;
- on Wayland the widget uses the layer-shell 'desktop' window type.
"""
from __future__ import annotations

import os

from . import fonts, paths
from .providers import font


def session_type() -> str:
    s = (os.environ.get("XDG_SESSION_TYPE") or "").lower()
    if s in ("wayland", "x11"):
        return s
    return "wayland" if os.environ.get("WAYLAND_DISPLAY") else "x11"


def _hex(color: str) -> str:
    c = (color or "#000000").lstrip("#")
    return c[:6].lower() if len(c) >= 6 else "000000"


def _lua_str(s: str) -> str:
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def generate(widget, session: str | None = None) -> str:
    session = session or session_type()
    ap = widget.appearance
    cache = paths.widget_cache_dir(widget.id)
    alpha = max(0, min(255, round(ap.opacity * 255 / 100)))

    if session == "wayland":
        output = ["out_to_x = false,", "out_to_wayland = true,"]
    else:
        output = ["out_to_x = true,", "out_to_wayland = false,",
                  "own_window_hints = 'undecorated,below,sticky,skip_taskbar,skip_pager',"]

    settings = output + [
        "own_window = true,",
        "own_window_type = 'desktop',",
        f"own_window_title = {_lua_str('widget-studio-' + widget.id)},",
        f"alignment = {_lua_str(widget.alignment)},",
        f"gap_x = {int(widget.gap_x)},",
        f"gap_y = {int(widget.gap_y)},",
        f"minimum_width = {int(widget.width)},",
        f"maximum_width = {int(widget.width)},",
        f"border_inner_margin = {int(widget.padding)},",
        "update_interval = 1,",
        "text_buffer_size = 8192,",
        "double_buffer = true,",
        "use_xft = true,",
        f"font = {_lua_str(f'{ap.text_font}:size={int(ap.text_size)}')},",
        "own_window_transparent = false,",
        "own_window_argb_visual = true,",
        f"own_window_argb_value = {alpha},",
        f"own_window_colour = '{_hex(ap.background)}',",
        "draw_borders = false,",
        "draw_shades = false,",
        "draw_outline = false,",
        "draw_graph_borders = false,",
        "default_bar_height = 4,",
        f"default_color = '{_hex(ap.text)}',",
        f"color1 = '{_hex(ap.highlight)}',",
        f"color2 = '{_hex(ap.lines)}',",
        f"color3 = '{_hex(ap.accent)}',",
        f"color4 = '{_hex(ap.dim)}',",
        "cpu_avg_samples = 2,",
        "no_buffers = true,",
    ]

    body = []
    sections = widget.active_sections()
    for i, name in enumerate(sections):
        if i > 0 and widget.dividers:
            body.append("${voffset 4}${color2}${hr 1}${color}")
        body.extend(_section(widget, name, cache))
    if not body:
        body.append("${alignc}${color4}TURN ON A SECTION IN WIDGET STUDIO${color}")

    return (
        "-- Generated by Widget Studio. Edit the widget in the app instead:\n"
        "-- your changes here will be overwritten.\n"
        # Conky only loads the font list when it starts. This line changes when a
        # font gets installed, so the widget restarts and picks the font up.
        f"-- fonts: {fonts.fingerprint(ap)}\n"
        "conky.config = {\n    " + "\n    ".join(settings) + "\n};\n\n"
        "conky.text = [[\n" + "\n".join(body) + "\n]];\n"
    )


def _section(widget, name: str, cache: str) -> list[str]:
    ap = widget.appearance
    disp = lambda size: font(ap.display_font, size, ap.display_bold)  # noqa: E731
    label = (lambda text: [f"${{color4}}{text}${{color}}"]) if widget.labels else (lambda text: [])

    if name == "clock":
        c = widget.clock
        fmt = ("%H:%M" if c.use_24h else "%I:%M") + (":%S" if c.seconds else "")
        clock = f"${{tztime {c.timezone} {fmt}}}" if c.timezone else f"${{time {fmt}}}"
        lines = [f"${{alignc}}{disp(c.size)}${{color3}}{clock}${{font}}${{color}}"]
        if not c.use_24h:
            ampm = f"${{tztime {c.timezone} %p}}" if c.timezone else "${time %p}"
            lines[0] = lines[0].replace("${font}${color}", f"${{font}} {ampm}${{color}}")
        if c.show_date:
            lines.append(f"${{alignc}}{disp(c.date_size)}${{catp {cache}/date.txt}}${{font}}")
        return lines

    if name == "weather":
        return label("WEATHER") + [f"${{catp {cache}/weather.txt}}${{font}}"]

    if name == "calendar":
        family, bold = fonts.calendar_font(ap)
        return [f"{font(family, widget.calendar.size, bold)}${{catp {cache}/calendar.txt}}${{font}}"]

    if name == "stats":
        s = widget.stats
        path = s.disk_path or "/"
        lines = label("SYSTEM")
        if s.cpu:
            lines.append("CPU${alignr}${cpu cpu0}%")
            if s.bars:
                lines.append("${color3}${cpubar cpu0 4}${color}")
        if s.ram:
            lines.append("RAM  ${mem} / ${memmax}${alignr}${memperc}%")
            if s.bars:
                lines.append("${color3}${membar 4}${color}")
        if s.disk:
            lines.append(f"DISK  ${{fs_used {path}}} / ${{fs_size {path}}}${{alignr}}${{fs_used_perc {path}}}%")
            if s.bars:
                lines.append(f"${{color3}}${{fs_bar 4 {path}}}${{color}}")
        if s.temperature:
            lines.append(f"CPU TEMP${{alignr}}${{catp {cache}/temp.txt}}")
        return lines

    return []
